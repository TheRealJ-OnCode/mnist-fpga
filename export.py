"""Export everything the FPGA needs: weights, biases, parameters and test vectors.

All .mem files are plain hex, one value per line, readable with Verilog $readmemh.
Negative numbers are written in two's complement.
"""

import os
import numpy as np
from reference import (q1, q2, b1_q, b2_q, M0, SHIFT, raw, labels,
                       downscale_int, layer1, layer2)

OUT_DIR = "export"
N_TEST = 100          # number of test images exported as test vectors


def hex8(v):
    """8-bit two's complement hex, e.g. -1 -> ff."""
    return f"{int(v) & 0xFF:02x}"


def hex32(v):
    """32-bit two's complement hex, e.g. -1 -> ffffffff."""
    return f"{int(v) & 0xFFFFFFFF:08x}"


def write_mem(filename, values, fmt):
    with open(os.path.join(OUT_DIR, filename), "w") as f:
        for v in values:
            f.write(fmt(v) + "\n")


def signed_bits(v):
    """Bits needed to hold a signed value with this magnitude."""
    return int(v).bit_length() + 1


os.makedirs(OUT_DIR, exist_ok=True)

# ---------------------------------------------------------------
# 1. Weights and biases
#    w1.mem: 16 x 196, row-major -> address = neuron * 196 + pixel
#    w2.mem: 10 x 16,  row-major -> address = neuron * 16 + hidden
# ---------------------------------------------------------------
write_mem("w1.mem", q1.flatten(), hex8)
write_mem("b1.mem", b1_q, hex32)
write_mem("w2.mem", q2.flatten(), hex8)
write_mem("b2.mem", b2_q, hex32)

# ---------------------------------------------------------------
# 2. Accumulator ranges over the full test set (for choosing bit widths)
# ---------------------------------------------------------------
max_acc1 = 0
max_req = 0
max_acc2 = 0
for i in range(len(labels)):
    x = downscale_int(raw[i])
    acc1 = q1.astype(np.int64) @ x + b1_q
    max_acc1 = max(max_acc1, np.abs(acc1).max())
    max_req = max(max_req, np.maximum(acc1, 0).max() * M0 + (1 << (SHIFT - 1)))
    acc2 = layer2(layer1(x))
    max_acc2 = max(max_acc2, np.abs(acc2).max())

# ---------------------------------------------------------------
# 3. Parameters as a Verilog header
# ---------------------------------------------------------------
with open(os.path.join(OUT_DIR, "params.vh"), "w") as f:
    f.write("// Generated by export.py - do not edit by hand\n")
    f.write("localparam N_IN     = 196;  // 14x14 input pixels, unsigned 8-bit\n")
    f.write("localparam N_HIDDEN = 16;   // hidden values, unsigned 8-bit\n")
    f.write("localparam N_OUT    = 10;   // output scores, signed 32-bit\n")
    f.write(f"localparam M0       = {M0};  // requantization multiplier\n")
    f.write(f"localparam SHIFT    = {SHIFT};   // requantization right shift\n")
    f.write(f"localparam ROUND    = {1 << (SHIFT - 1)};  // added before the shift\n")
    f.write(f"// Observed on 10000 test images:\n")
    f.write(f"//   max |acc1|          = {max_acc1} ({signed_bits(max_acc1)} bits signed)\n")
    f.write(f"//   max acc1*M0 + ROUND = {max_req} ({signed_bits(max_req)} bits signed)\n")
    f.write(f"//   max |acc2|          = {max_acc2} ({signed_bits(max_acc2)} bits signed)\n")

# ---------------------------------------------------------------
# 4. Test vectors: input, hidden layer, scores and prediction
#    for the first N_TEST test images
# ---------------------------------------------------------------
images, hiddens, scores, preds = [], [], [], []
expected_lines = []
for i in range(N_TEST):
    x = downscale_int(raw[i])
    h = layer1(x)
    s = layer2(h)
    p = int(s.argmax())        # ties: first (lowest) index wins
    images.extend(x)
    hiddens.extend(h)
    scores.extend(s)
    preds.append(p)
    expected_lines.append(f"{i:3d}  label {labels[i]}  prediction {p}")

write_mem("test_images.mem", images, hex8)     # N_TEST x 196
write_mem("test_hidden.mem", hiddens, hex8)    # N_TEST x 16
write_mem("test_scores.mem", scores, hex32)    # N_TEST x 10
write_mem("test_pred.mem", preds, hex8)        # N_TEST x 1

with open(os.path.join(OUT_DIR, "test_expected.txt"), "w") as f:
    f.write("\n".join(expected_lines) + "\n")

correct = sum(1 for i in range(N_TEST) if preds[i] == labels[i])

# ---------------------------------------------------------------
# Summary
# ---------------------------------------------------------------
print()
print("Exported to", OUT_DIR + "/")
for name in sorted(os.listdir(OUT_DIR)):
    print("  ", name)
print(f"max |acc1|          = {max_acc1} -> {signed_bits(max_acc1)} bits")
print(f"max acc1*M0 + ROUND = {max_req} -> {signed_bits(max_req)} bits")
print(f"max |acc2|          = {max_acc2} -> {signed_bits(max_acc2)} bits")
print(f"accuracy on the {N_TEST} exported test images: {correct}/{N_TEST}")